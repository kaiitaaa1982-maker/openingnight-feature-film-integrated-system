import {openPgClient} from './pg-client.mjs';
import {PgDatabase} from '../src/data-platform/pg-db.mjs';
export const exportSchema = `
CREATE TABLE schema_source_fingerprint(expected_tables bigint, ddl_sha256 text);
INSERT INTO schema_source_fingerprint VALUES(2, 'fictional-export-schema-v1');
CREATE TABLE sales_source_files(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, original_base64 text, amount_yen bigint, precise numeric, bytes bytea);
CREATE TABLE z_children(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_id bigint REFERENCES sales_source_files(id), amount_yen bigint);
CREATE FUNCTION no_update() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'immutable'; END $$;
CREATE TRIGGER frozen BEFORE UPDATE ON sales_source_files FOR EACH ROW EXECUTE FUNCTION no_update();
`;
export async function exportFixture(t, {empty = false} = {}) {
  const connection = await openPgClient({applySchema: false});
  t.after(() => connection.close());
  if (!empty) await connection.client.query(exportSchema);
  return {...connection, db: new PgDatabase(connection.client)};
}
export function memoryBucket(onPut = async () => {}) {
  const objects = new Map();
  return {objects,
    async put(key, value) {
      await onPut(key);
      objects.set(key, Buffer.from(typeof value === 'string' ? value : value));
      return {key};
    },
    async get(key) {
      const value = objects.get(key);
      return value ? {size: value.length, body: true, text: async () => value.toString(), arrayBuffer: async () => value} : null;
    },
  };
}
